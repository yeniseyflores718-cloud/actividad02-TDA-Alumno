    /** Convierte un texto como "8, 9.5, 7" en un arreglo de double. */
    private double[] leerCalificaciones(String texto) {
        // Separa el texto usando la coma como divisor
        String[] partes = texto.split(",");
        double[] resultado = new double[partes.length];

        // Convierte cada parte a número (lanza NumberFormatException si no es válido)
        for (int i = 0; i < partes.length; i++) {
            resultado[i] = Double.parseDouble(partes[i].trim());
        }
        return resultado;
    }
