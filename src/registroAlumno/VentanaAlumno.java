    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        try {
        int edad = Integer.parseInt(txtEdad.getText().trim());
        double[] calificaciones = leerCalificaciones(txtPromedio.getText());

        // Variable de tipo Alumno
        Alumno alumno;

        if (chkUniversitario.isSelected()) {
            // Universitario: la carrera es obligatoria y la valida la propia clase
            alumno = new AlumnoUniversitario(txtNombre.getText(), txtMatricula.getText(),
                    edad, calificaciones, txtCarrera.getText());
        } else {
            // Alumno común: no lleva carrera
            alumno = new Alumno(txtNombre.getText(), txtMatricula.getText(),
                    edad, calificaciones);
        }

        // Se ejecuta la versión de obtenerResumen() que corresponda al objeto real
        txtResultado.setText(alumno.obtenerResumen());

    } catch (NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "La edad y las calificaciones deben ser números válidos.",
                "Dato inválido", javax.swing.JOptionPane.WARNING_MESSAGE);
    } catch (IllegalArgumentException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                "Dato inválido", javax.swing.JOptionPane.WARNING_MESSAGE);
    }
    }//GEN-LAST:event_btnRegistrarActionPerformed

